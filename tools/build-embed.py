#!/usr/bin/env python3
"""Build the Webflow embed version of the tool from index.html.

index.html stays the single source of truth (it is also the GitHub Pages site).
Run after every change to index.html:   python3 tools/build-embed.py

Outputs (served by GitHub Pages, loaded by the Webflow page):
  embed/amr.css            styles, scoped to #amr-app so they never touch the rest of the site
  embed/amr.js             all logic + the tool's UI markup (auto-updates on Webflow)
  embed/webflow-body.html  paste ONCE into a Webflow Embed element (SEO text + mount point)
  embed/webflow-head.html  paste ONCE into the Webflow page's <head> custom code (schema)
"""
import json, re, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
PAGES = 'https://atiq31416.github.io/aimetadataremover/'
LIVE = 'https://www.designmonks.co/aimetadataremover'
S = 'amr-app'

src = (ROOT / 'index.html').read_text(encoding='utf-8')
out = ROOT / 'embed'; out.mkdir(exist_ok=True)

# ---------------- CSS ----------------
css = re.search(r'<style>(.*?)</style>', src, re.S).group(1)
css = re.sub(r':root\[data-theme="light"\].*?(?=:root|$|\/\*)', '', css, flags=re.S)

P = 'amr-'   # prefix for every class and id, so nothing clashes with the host site
def px_sel(sel):
    sel = re.sub(r'\.([A-Za-z][\w-]*)', lambda m: '.' + P + m.group(1), sel)
    return re.sub(r'#([A-Za-z][\w-]*)', lambda m: '#' + (m.group(1) if m.group(1) == S else P + m.group(1)), sel)

def px_code(t):
    pre = lambda tok: tok if (not tok or '$' in tok or '{' in tok or '}' in tok) else P + tok
    t = re.sub(r'class="([^"]*)"', lambda m: 'class="' + ' '.join(pre(x) for x in m.group(1).split(' ')) + '"', t)
    t = re.sub(r"(classList\.(?:add|remove|toggle)\(')([\w-]+)", lambda m: m.group(1) + P + m.group(2), t)
    t = re.sub(r"(className = ')([\w-]+)", lambda m: m.group(1) + P + m.group(2), t)
    t = re.sub(r'(\bid|aria-labelledby)="([A-Za-z][\w-]*)"', lambda m: f'{m.group(1)}="{P}{m.group(2)}"', t)
    t = re.sub(r"(\$\('#|getElementById\(')([A-Za-z][\w-]*)", lambda m: m.group(1) + P + m.group(2), t)
    t = re.sub(r"(\['#)([A-Za-z][\w-]*)(', '#)([A-Za-z][\w-]*)", lambda m: m.group(1)+P+m.group(2)+m.group(3)+P+m.group(4), t)
    return t

def scope_rules(block):
    res, i = [], 0
    while i < len(block):
        j = block.find('{', i)
        if j < 0: res.append(block[i:]); break
        sel = block[i:j].strip()
        if sel.startswith('@media'):
            depth, k = 1, j + 1
            while depth:
                depth += {'{': 1, '}': -1}.get(block[k], 0); k += 1
            res.append(f'{sel}{{{scope_rules(block[j+1:k-1])}}}\n'); i = k; continue
        if sel.startswith('@keyframes'):
            depth, k = 1, j + 1
            while depth:
                depth += {'{': 1, '}': -1}.get(block[k], 0); k += 1
            name = sel.split()[1]
            res.append(f'@keyframes {S}-{name}{block[j:k]}\n'); i = k; continue
        k = block.find('}', j)
        body_rule = block[j+1:k]
        parts = []
        for s_ in sel.split(','):
            s_ = s_.strip()
            if s_ in (':root', 'body'): parts.append(f'#{S}')
            elif s_ == '*': parts.extend([f'#{S}', f'#{S} *'])
            else: parts.append(f'#{S} {px_sel(s_)}')
        res.append(f'{",".join(parts)}{{{body_rule}}}\n'); i = k + 1
    return ''.join(res)

scoped = scope_rules(css)
scoped = scoped.replace('animation:s ', f'animation:{S}-s ')
reset = f'''/* AI Metadata Remover, Webflow embed. Generated by tools/build-embed.py, do not edit by hand. */
@import url('https://fonts.googleapis.com/css2?family=Plus+Jakarta+Sans:wght@400;500;600;700;800;900&family=JetBrains+Mono:wght@400;500&display=swap');
#{S} h1,#{S} h2,#{S} h3,#{S} h4,#{S} p,#{S} ul,#{S} ol,#{S} label,#{S} figure{{margin:0}}
#{S} h1,#{S} h2,#{S} h3,#{S} h4{{font-family:inherit;color:inherit;line-height:1.25;font-weight:700}}
#{S} label{{font-weight:inherit;display:inline}}
#{S} ul,#{S} ol{{padding:0}}
#{S} img{{max-width:none}}
'''
font_fix = f'\n#{S}{{font-family:var(--ui);font-size:16px;line-height:1.5;color:var(--text)}}\n#{S}{{background:transparent}}\n'
(out / 'amr.css').write_text(reset + scoped + font_fix, encoding='utf-8')

# ---------------- markup ----------------
wrap_match = re.search(r'<div class="wrap"[^>]*>(.*?)</div>\s*(?:</main>|<footer|<script)', src, re.S)
body = wrap_match.group(1) if wrap_match else ''
tool_start = body.index('  <label class="drop"')
tool_end = body.index('<div class="list" id="list" data-ui></div>') + len('<div class="list" id="list" data-ui></div>')
header, tool, rest = (px_code(x) for x in (body[:tool_start], body[tool_start:tool_end], body[tool_end:]))
rest = rest.replace('src="demo-', f'src="{PAGES}demo-').replace('poster="demo-', f'poster="{PAGES}demo-')

# ---------------- JS ----------------
scripts = re.findall(r'<script(?: id="core")?>(.*?)</script>', src, re.S)
js = px_code('\n'.join(scripts))
js = (f'/* AI Metadata Remover, Webflow embed. Generated by tools/build-embed.py, do not edit by hand. */\n'
      f'(function(){{\n"use strict";\n'
      f'var mount = document.getElementById("amr-tool");\n'
      f'if (!mount) return;\n'
      f'mount.innerHTML = {json.dumps(tool.strip())};\n'
      f'{js}\n}})();\n')
(out / 'amr.js').write_text(js, encoding='utf-8')

# ---------------- Webflow snippets ----------------
v = '2'  # bump to force browsers to fetch new CSS after big changes
snippet = f'''<link rel="stylesheet" href="{PAGES}embed/amr.css?v={v}">
<div id="{S}"><div class="{P}wrap">
{header.rstrip()}
  <div id="amr-tool"><noscript><p>Please turn on JavaScript to use the AI Metadata Remover.</p></noscript></div>
{rest.rstrip()}
</div></div>
<script src="{PAGES}embed/amr.js?v={v}" defer></script>
'''
(out / 'webflow-body.html').write_text(snippet, encoding='utf-8')

ld = re.search(r'<script type="application/ld\+json">(.*?)</script>', src, re.S).group(1)
ld = ld.replace(PAGES.rstrip('/') + '/#', LIVE + '#').replace(PAGES + 'og-image.png', PAGES + 'og-image.png').replace(f'"url": "{PAGES}"', f'"url": "{LIVE}"')
(out / 'webflow-head.html').write_text(f'<script type="application/ld+json">{ld}</script>\n', encoding='utf-8')

print('embed/amr.css', len(reset + scoped + font_fix), 'chars')
print('embed/amr.js', len(js), 'chars')
print('embed/webflow-body.html', len(snippet), 'chars (Webflow limit 50,000)')
print('embed/webflow-head.html', len(ld) + 40, 'chars')
